/**
 * Find product by ID
 */
function getProductById(id) {
    return PRODUCTS_DATA.find(product => product.id === id);
}


/**
 * Find products by category
 */
function getProductsByCategory(categoryId) {
    return PRODUCTS_DATA.filter(
        product => product.categoryId === categoryId
    );
}


/**
 * Find service by ID
 */
function getServiceById(id) {
    return SERVICES_DATA.find(service => service.id === id);
}


/**
 * Find gallery items by category
 */
function getGalleryByCategory(category) {
    return GALLERY_DATA.filter(
        item => item.category === category
    );
}


/**
 * Get category by ID
 */
function getCategoryById(id) {
    return PRODUCT_CATEGORIES.find(
        category => category.id === id
    );
}


/**
 * Get WhatsApp URL
 */
function getWhatsAppUrl(message = "") {

    const encodedMessage = encodeURIComponent(message);

    return `https://wa.me/${SITE_CONFIG.whatsappNumber}?text=${encodedMessage}`;
}


/**
 * Get phone URL
 */
function getPhoneUrl() {
    return `tel:${SITE_CONFIG.phoneNumber.replace(/\s+/g, "")}`;
}


/**
 * Get email URL
 */
function getEmailUrl() {
    return `mailto:${SITE_CONFIG.email}`;
}


